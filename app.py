def editor_required(f):
    @wraps(f)
    def inner(*args, **kwargs):
        if not session.get("authenticated"):
            return (jsonify(error="Editor login required"), 401) if request.path.startswith("/api/") else redirect(url_for("login"))
        return f(*args, **kwargs)
    return inner

def same_origin():
    origin = request.headers.get("Origin")
    if not origin:
        return True
    try:
        uri = urlparse(origin)
        return uri.netloc.lower() == request.host.lower() and uri.scheme in ("http","https")
    except Exception:
        return False

@app.after_request
def secure(resp):
    resp.headers["Cache-Control"] = "no-store"
    resp.headers["X-Content-Type-Options"] = "nosniff"
    resp.headers["X-Frame-Options"] = "DENY"
    resp.headers["Referrer-Policy"] = "strict-origin-when-cross-origin"
    resp.headers["Content-Security-Policy"] = "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self'; object-src 'none'; base-uri 'self'; frame-ancestors 'none'"
    if request.is_secure:
        resp.headers["Strict-Transport-Security"] = "max-age=31536000; includeSubDomains"
    return resp

