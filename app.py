@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "GET":
        return redirect("/") if session.get("authenticated") else render_template_string(LOGIN_HTML, error=None)
    if not same_origin():
        return "Untrusted request origin", 403
    candidate = request.form.get("password", "")
    if hmac.compare_digest(candidate.encode(), ADMIN_PASSWORD.encode()):
        session.clear()
        session["authenticated"] = True
        session.permanent = True
        return redirect("/")
    return render_template_string(LOGIN_HTML, error="Incorrect password"), 401

