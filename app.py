PRIVATE_TABLES = {"evidence", "legacySacaArchive", "legacyEssentialQuarterly"}
PRIVATE_FIELDS = {
    "owner", "responsibleperson", "responsiblepartner", "documenttitle",
    "notes", "activitynotes", "keyfindings", "datasource", "officialsourceperiod",
    "primarydocumenturl", "documenturl", "evidenceurl", "primaryevidenceurl",
    "savedby", "email", "phone", "participantname", "beneficiaryname", "secret"
}
def public_snapshot(payload):
    if not isinstance(payload, dict):
        return None
    safe = {}
    for name, val in payload.items():
        if name in PRIVATE_TABLES:
            safe[name] = []
        elif isinstance(val, list):
            cleaned = []
            for obj in val:
                if not isinstance(obj, dict):
                    cleaned.append(obj)
                    continue
                cleaned.append({
                    k:v for k,v in obj.items()
                    if k.lower() not in PRIVATE_FIELDS and not k.lower().endswith("url")
                    and not any(s in k.lower() for s in ("password", "token", "credential"))
                })
            safe[name] = cleaned
        elif name in ("version", "savedAt"):
            safe[name] = val
    return safe

@app.get("/api/state")
def get_state():
    with connect() as con:
        cur = con.cursor()
        cur.execute("SELECT revision,payload,updated_at FROM rbm_state WHERE id=1")
        row = cur.fetchone()
    data = json.loads(row["payload"]) if row["payload"] else None
    if not session.get("authenticated"):
        data = public_snapshot(data)
    return jsonify(revision=row["revision"],updated_at=row["updated_at"],payload=data)

@app.put("/api/state")
@editor_required
def put_state():
    if not same_origin():
        return jsonify(error="Untrusted request origin"), 403
    body = request.get_json(silent=True)
    if not isinstance(body, dict) or type(body.get("revision")) is not int or not isinstance(body.get("payload"), dict):
        return jsonify(error="Invalid request"), 400
    payload = body["payload"]
    if payload.get("version") != 7 or not isinstance(payload.get("indicators"), list) or not isinstance(payload.get("rbmActivities"), list):
        return jsonify(error="Unsupported state version or missing indicator/activity records"), 400
    if len(payload["indicators"]) > 3000 or len(payload["rbmActivities"]) > 50000:
        return jsonify(error="Storage limits exceeded"), 413
    serialized = json.dumps(payload, ensure_ascii=False, separators=(",",":"))
    if len(serialized.encode()) > 7*1024*1024:
        return jsonify(error="State exceeds 7MB"), 413
    now = datetime.now(timezone.utc).isoformat()
    con = connect()
    try:
        if not POSTGRES:
            con.execute("BEGIN IMMEDIATE")
        cur = con.cursor()
        cur.execute("SELECT revision,payload FROM rbm_state WHERE id=1" + (" FOR UPDATE" if POSTGRES else ""))
        old = cur.fetchone()
        revision = int(old["revision"])
        if revision != body["revision"]:
            con.rollback()
            return jsonify(error="Concurrent edit detected. Export a backup before reloading.",current_revision=revision), 409
        if old["payload"]:
            cur.execute("INSERT INTO rbm_backups (revision,payload,saved_at) VALUES (" + ("%s,%s,%s" if POSTGRES else "?,?,?") + ")",(revision,old["payload"],now))
        cur.execute("UPDATE rbm_state SET revision=" + ("%s" if POSTGRES else "?") + ",payload=" + ("%s" if POSTGRES else "?") + ",updated_at=" + ("%s" if POSTGRES else "?") + " WHERE id=1", (revision+1,serialized,now))
        con.commit()
    finally:
        con.close()
    return jsonify(ok=True,revision=revision+1,updated_at=now)

@app.get("/api/backups")
@editor_required
def list_backups():
    with connect() as con:
        cur = con.cursor()
        cur.execute("SELECT id,revision,saved_at FROM rbm_backups ORDER BY id DESC LIMIT 200")
        rows = [dict(r) for r in cur.fetchall()]
    return jsonify(backups=rows)

@app.get("/api/backups/<int:backup_id>")
@editor_required
def download_backup(backup_id):
    with connect() as con:
        cur = con.cursor()
        cur.execute("SELECT payload FROM rbm_backups WHERE id=" + ("%s" if POSTGRES else "?"),(backup_id,))
        row = cur.fetchone()
    if row is None:
        return jsonify(error="Backup not found"), 404
    return Response(row["payload"],mimetype="application/json",headers={"Content-Disposition":f"attachment; filename=RBM_backup_{backup_id}.json"})

