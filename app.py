def bootstrap():
    with connect() as con:
        c = con.cursor()
        c.execute("CREATE TABLE IF NOT EXISTS rbm_state (id INTEGER PRIMARY KEY, revision INTEGER NOT NULL DEFAULT 0, payload TEXT, updated_at TEXT)")
        identity = "GENERATED BY DEFAULT AS IDENTITY" if POSTGRES else "AUTOINCREMENT"
        c.execute("CREATE TABLE IF NOT EXISTS rbm_backups (id INTEGER PRIMARY KEY " + identity + ", revision INTEGER NOT NULL, payload TEXT NOT NULL, saved_at TEXT NOT NULL)")
        c.execute("INSERT INTO rbm_state (id,revision,payload,updated_at) VALUES (1,0,NULL,NULL) " + ("ON CONFLICT (id) DO NOTHING" if POSTGRES else "ON CONFLICT (id) DO NOTHING"))
